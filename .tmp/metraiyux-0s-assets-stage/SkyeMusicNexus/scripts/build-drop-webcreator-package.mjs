#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { _internal } = require('../netlify/functions/music-drops.js');

function arg(name, fallback = '') {
  const prefix = `--${name}=`;
  const hit = process.argv.find((item) => item.startsWith(prefix));
  return hit ? hit.slice(prefix.length) : fallback;
}

const input = arg('input');
const outDir = arg('out', process.cwd());
if (!input) {
  console.error('Usage: node scripts/build-drop-webcreator-package.mjs --input=drop.json --out=/tmp/drop-package');
  process.exit(1);
}

const drop = JSON.parse(await fs.readFile(input, 'utf8'));
const batch = { batchId: drop.batchId || 'manual-webcreator-package' };
const growth = {
  seo: {
    title: `${drop.artistName || drop.artistId || 'Artist'} - ${drop.title}`,
    description: drop.story || `SkyeMusicNexus drop page for ${drop.title}.`,
  },
};
const pkg = _internal.buildWebCreatorPackage(drop, batch, growth);
await fs.mkdir(outDir, { recursive: true });
await fs.writeFile(path.join(outDir, 'webcreator-package.json'), JSON.stringify(pkg, null, 2) + '\n', 'utf8');
await fs.writeFile(path.join(outDir, 'README.md'), [
  '# SkyeWebCreatorMax Drop Package',
  '',
  'Generated by SkyeMusicNexus as a bridge payload for SkyeWebCreatorMax.',
  'The source app is referenced, not copied.',
  '',
].join('\n'), 'utf8');
console.log(JSON.stringify({ ok: true, outputDir: outDir, package: pkg }, null, 2));
