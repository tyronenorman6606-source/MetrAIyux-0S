import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveZeroOsGateAuth } from '../../tools/lib/zero-os-gate-auth.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

function loadDotEnv() {
  const file = path.join(root, '.env');
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const index = trimmed.indexOf('=');
    if (index === -1) continue;
    const key = trimmed.slice(0, index).trim();
    let value = trimmed.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = value;
  }
}

function requiredEnv(name) {
  if (!process.env[name]) {
    console.error(`Missing required env: ${name}`);
    process.exit(1);
  }
}

function firstAllowedOrigin() {
  const configured = String(process.env.ALLOWED_ORIGINS || '').split(',').map((x) => x.trim()).filter(Boolean);
  if (configured.length && configured[0] !== '*') return configured[0];
  return process.env.URL || 'http://localhost:8888';
}

function event(method, body = null, headers = {}, queryStringParameters = {}) {
  return {
    httpMethod: method,
    headers: {
      origin: firstAllowedOrigin(),
      ...headers
    },
    queryStringParameters,
    body: body ? JSON.stringify(body) : ''
  };
}

async function call(name, handler, evt) {
  const response = await handler(evt);
  const data = response.body ? JSON.parse(response.body) : null;
  if (response.statusCode < 200 || response.statusCode >= 300 || data?.ok === false) {
    console.error(`❌ ${name} failed`, response.statusCode, data || response.body);
    process.exit(1);
  }
  console.log(`✅ ${name} passed`);
  return data;
}

loadDotEnv();
requiredEnv('R2_ACCOUNT_ID');
requiredEnv('R2_ACCESS_KEY_ID');
requiredEnv('R2_SECRET_ACCESS_KEY');
requiredEnv('R2_BUCKET');
if (!process.env.R2_CONFIG_PREFIX && !process.env.R2_CONFIG_FOLDER_ID && !process.env.GOOGLE_CONFIG_FOLDER_ID) {
  console.error('Missing required env: R2_CONFIG_PREFIX');
  process.exit(1);
}

const gateAuth = await resolveZeroOsGateAuth({ envFiles: [path.join(root, '.env'), path.join(root, '..', '.env'), path.join(root, '..', 'env.txt')] });
if (!gateAuth.ok || !gateAuth.token) {
  console.error('Missing shared FS27/SkyGate bearer for SkyeVault live smoke.');
  process.exit(1);
}
const adminHeaders = { authorization: `Bearer ${gateAuth.token}`, 'x-skye-gate-session': gateAuth.token };
const portalHeaders = process.env.CLIENT_PORTAL_KEY ? { 'x-portal-key': process.env.CLIENT_PORTAL_KEY } : {};

const [{ handler: publicConfig }, { handler: adminConfig }, { handler: adminDriveTest }, { handler: uploadSession }, { handler: uploadComplete }, { handler: uploadStatus }] = await Promise.all([
  import('../netlify/functions/public-config.js'),
  import('../netlify/functions/admin-config.js'),
  import('../netlify/functions/admin-drive-test.js'),
  import('../netlify/functions/upload-session.js'),
  import('../netlify/functions/upload-complete.js'),
  import('../netlify/functions/upload-status.js')
]);

const publicData = await call('public config load', publicConfig, event('GET'));
if (!publicData.config?.destinations?.length) {
  console.error('❌ No enabled public destinations are configured. Save at least one destination first.');
  process.exit(1);
}

await call('admin config load', adminConfig, event('GET', null, adminHeaders, { ledger: 'true' }));
const storageTest = await call('admin R2 write test', adminDriveTest, event('POST', { writeTest: true }, adminHeaders));
const failed = (storageTest.results || []).filter((result) => !result.ok);
if (failed.length) {
  console.error('❌ One or more destinations failed R2 write test:', failed.map((item) => `${item.id}: ${item.error}`).join('; '));
  process.exit(1);
}

const fileText = `SkyeVault-Drop live smoke ${new Date().toISOString()}\n`;
const fileBuffer = Buffer.from(fileText, 'utf8');
const fileFingerprint = {
  algorithm: 'SHA-256',
  mode: 'full',
  value: crypto.createHash('sha256').update(fileBuffer).digest('hex'),
  bytesHashed: fileBuffer.length,
  generatedAt: new Date().toISOString(),
  note: 'Full SHA-256 generated by live R2 smoke script.'
};
const fileName = `client-drop-vault-live-smoke-${Date.now()}.txt`;
const uploadBody = {
  clientName: 'Live Smoke Test',
  clientEmail: 'smoke@example.com',
  projectName: 'Deployment Proof',
  clientReference: 'LIVE-SMOKE',
  assetType: 'Launch / handoff docs',
  notes: 'Generated by scripts/live-drive-smoke.mjs',
  clientRequestId: `live-smoke-${Date.now()}`,
  submissionId: `live-submission-${Date.now()}`,
  usageRightsAccepted: true,
  retentionAcknowledged: true,
  portalKey: process.env.CLIENT_PORTAL_KEY || '',
  destinationId: process.env.TEST_DESTINATION_ID || '',
  fileName,
  fileSize: fileBuffer.length,
  mimeType: 'text/plain',
  fileFingerprint,
  failedDestinationIds: []
};

const session = await call('upload session creation', uploadSession, event('POST', uploadBody, portalHeaders));
const completedParts = [];
for (const part of session.parts || []) {
  const uploadResponse = await fetch(part.uploadUrl, {
    method: 'PUT',
    body: fileBuffer.subarray(part.start, part.end + 1)
  });
  const uploadText = await uploadResponse.text();
  if (!uploadResponse.ok) {
    console.error('❌ direct Cloudflare R2 part upload failed', uploadResponse.status, uploadText.slice(0, 500));
    process.exit(1);
  }
  completedParts.push({
    partNumber: part.partNumber,
    eTag: (uploadResponse.headers.get('etag') || uploadResponse.headers.get('ETag') || '').replace(/^"|"$/g, '')
  });
}
const driveFile = {
  ...(session.r2Object || {}),
  id: session.objectKey,
  key: session.objectKey,
  bucket: session.bucket,
  uploadId: session.uploadId,
  parts: completedParts,
  name: fileName,
  size: String(fileBuffer.length),
  mimeType: 'text/plain'
};
if (!driveFile.id || !driveFile.uploadId || !driveFile.parts.length) {
  console.error('❌ R2 upload session did not return multipart object proof', driveFile);
  process.exit(1);
}
console.log(`✅ direct Cloudflare R2 multipart upload passed: ${driveFile.id}`);

const completion = await call('upload completion signed receipt + ledger write', uploadComplete, event('POST', {
  ...uploadBody,
  sessionId: session.sessionId,
  destinationId: session.destination.id,
  destinationName: session.destination.name,
  driveFileId: driveFile.id,
  driveFile
}, portalHeaders));
if (!completion.entry?.id || !completion.receipt?.id || !completion.manifest?.updated) {
  console.error('❌ completion did not return a receipt ID', completion);
  process.exit(1);
}
console.log(`✅ signed receipt + session manifest proof returned: ${completion.receipt.id}`);

const statusBySession = await call('upload status lookup by session', uploadStatus, event('POST', { sessionId: session.sessionId, portalKey: process.env.CLIENT_PORTAL_KEY || '' }, portalHeaders));
if (statusBySession.manifest?.status !== 'complete' || statusBySession.manifest?.receiptId !== completion.entry.id) {
  console.error('❌ status lookup by session did not return completed manifest proof', statusBySession);
  process.exit(1);
}

const statusByReceipt = await call('upload status lookup by receipt', uploadStatus, event('POST', { receiptId: completion.entry.id, portalKey: process.env.CLIENT_PORTAL_KEY || '' }, portalHeaders));
if (statusByReceipt.receipt?.id !== completion.entry.id) {
  console.error('❌ status lookup by receipt did not return receipt proof', statusByReceipt);
  process.exit(1);
}
console.log('✅ status lookup proof passed');

console.log('✅ Live Cloudflare R2 smoke completed end-to-end.');
