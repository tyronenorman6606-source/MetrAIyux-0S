import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'cloudflare', 'internal-pages.generated.mjs');

async function readPage(name) {
  return fs.readFile(path.join(root, 'internal-pages', `${name}.html`), 'utf8');
}

const [admin, setup] = await Promise.all([readPage('admin'), readPage('setup')]);
const banner = '// Generated by scripts/build-cloudflare-internal-pages.mjs. Do not edit by hand.\n';
const body = `${banner}export const ADMIN_HTML = ${JSON.stringify(admin)};\n\nexport const SETUP_HTML = ${JSON.stringify(setup)};\n`;

await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, body);
console.log(`Wrote ${path.relative(root, output)}`);
