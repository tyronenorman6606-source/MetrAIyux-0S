#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = process.cwd();
const indexPath = path.join(repoRoot, 'metraiyux_0s_site', 'skyenet', 'index.html');
const jsPath = path.join(repoRoot, 'metraiyux_0s_site', 'skyenet', 'skyenet.js');
const cssPath = path.join(repoRoot, 'metraiyux_0s_site', 'skyenet', 'skyenet.css');

const html = fs.readFileSync(indexPath, 'utf8');
const js = fs.readFileSync(jsPath, 'utf8');
const css = fs.readFileSync(cssPath, 'utf8');

assert.match(html, /id="dropZone"/, 'SkyeNet console must expose a visible drop zone.');
assert.match(html, /id="skrucibleEnhance"/, 'SkyeNet console must expose the Skrucible forge toggle.');
assert.match(html, /id="publishResult"/, 'SkyeNet console must expose the direct live link result panel.');
assert.match(html, /class="[^"]*skynet-tutorial-panel/, 'SkyeNet console must include a compact publish tutorial panel.');
assert.ok(html.indexOf('id="authPanel"') < html.indexOf('id="dropZone"'), 'The drop zone must sit directly after the login/gate panel region.');
assert.match(html, /metraiyux-0s-emblem-transparent\.png/, 'SkyeNet brand mark must use a real 0S logo asset.');
assert.doesNotMatch(html, /<span class="skynet-brand-mark">SN<\/span>/, 'SkyeNet must not fall back to an initial-tile logo.');

assert.match(js, /function stripSharedRoot/, 'Folder drop must strip wrapper roots before upload.');
assert.match(js, /function promoteBuildRoot/, 'Folder drop must promote common dist/build/out/public roots before upload.');
assert.match(js, /ROOT|index\.html|prepared\.meta\.has_index/i, 'Deploy flow must block bundles without a root index.');
assert.match(js, /function filesFromDataTransfer/, 'Folder drop must read DataTransfer directory entries.');
assert.match(js, /function prepareFilesForDeploy/, 'Deploy flow must prepare files before upload.');
assert.match(js, /function generateSkrucibleCss/, 'Skrucible CSS asset must be generated by the console.');
assert.match(js, /function generateSkrucibleJs/, 'Skrucible JS asset must be generated by the console.');
assert.match(js, /skyenet-skrucible-manifest\.json/, 'Skrucible deploys must include a manifest receipt file.');
assert.match(js, /source: 'skyenet-console-folder-drop'/, 'Complete manifest must record the folder-drop source.');

assert.match(css, /\.file-drop\.is-dragover/, 'Drop zone must have a drag-over state.');
assert.match(css, /\.surface-preview/, 'Surface preview panel must be styled.');
assert.match(css, /\.preview-forge\.armed/, 'Skrucible armed state must be visible.');
assert.match(css, /\.skynet-brand-mark img/, 'Real logo image must be styled in the brand mark.');
assert.match(css, /\.direct-live-link/, 'The direct live link must be styled as a visible blue link.');
assert.match(css, /\.tutorial-list/, 'The publish tutorial must be styled.');

const receipt = {
  ok: true,
  generated_at: new Date().toISOString(),
  checks: 22,
  files: {
    index: path.relative(repoRoot, indexPath),
    js: path.relative(repoRoot, jsPath),
    css: path.relative(repoRoot, cssPath)
  }
};

const out = path.join(repoRoot, 'test-artifacts', 'skyenet-drop-ui-proof.json');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(receipt, null, 2));
console.log(JSON.stringify(receipt, null, 2));
